package.path = "src/?.lua;" .. package.path
local A = dofile("tests/assert.lua")
local keys = require("keys")
local kb = {field=nil,buffer="",pressed={},order=0,profile="warp",bomb_size=1}

local action = keys.handle(kb,"key","up",false)
A.eq(action.x,1,"forward key")
action = keys.handle(kb,"key","down",false)
A.eq(action.x,-1,"newest axis key")
action = keys.handle(kb,"key_up","down")
A.eq(action.x,1,"axis fallback")
action = keys.handle(kb,"key_up","up")
A.eq(action.x,0,"axis release")

action = keys.handle(kb,"key","y",false)
A.eq(action,nil,"field start")
A.eq(kb.field,"altitude","altitude field")
keys.handle(kb,"char","-")
keys.handle(kb,"char","1")
keys.handle(kb,"char","2")
keys.handle(kb,"char",".")
keys.handle(kb,"char","5")
action = keys.handle(kb,"key","enter",false)
A.eq(action.type,"altitude","altitude action")
A.eq(action.value,-12.5,"altitude value")

keys.handle(kb,"key","b",false)
keys.handle(kb,"char","3")
keys.handle(kb,"char","7")
keys.handle(kb,"char","0")
action = keys.handle(kb,"key","numPadEnter",false)
A.near(action.value,math.rad(10),1e-12,"bearing wraps")

keys.handle(kb,"key","v",false)
action = keys.handle(kb,"key","enter",false)
A.eq(action.type,"message","bad number action")
A.eq(action.message,"not a number","bad number message")
A.eq(keys.handle(kb,"key","m",true),nil,"held single ignored")
A.eq(keys.handle(kb,"key","m",false).mode,"manual","manual key")
A.eq(keys.handle(kb,"key","w",false).profile,"cruise","profile toggle")
A.eq(keys.handle(kb,"key","rightBracket",false).size,3,"bomb size next")
A.eq(keys.handle(kb,"key","leftBracket",false).size,1,"bomb size previous")
